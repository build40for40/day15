"""Regenerates apps/web/src/alignment-circle.ts from concepts/a-line/a-line.html.

The page is the source of truth. The app runs it inside a shadow root so its
styles cannot touch the rest of the app. Run from the repo root:
    python3 concepts/a-line/port.py
"""
import re, json

s = open('concepts/a-line/a-line.html').read()

# ---------- CSS ----------
css = s[s.index('<style>') + 7: s.index('</style>')]
def crep(old, new):
    global css
    assert old in css, old[:60]
    css = css.replace(old, new, 1)
crep("html, body { background: var(--midnight); }\n", "")
body_rule = re.search(r"body \{ margin: 0;.*?padding-block: 0 56px; \}", css, re.S)
assert body_rule
css = css.replace(body_rule.group(0), ".root { color: var(--text); font-family: var(--sans); font-size: 15px; line-height: 1.55; -webkit-font-smoothing: antialiased; border-radius: 12px; container-type: inline-size;\n  background: radial-gradient(120% 70% at 50% -10%, var(--midnight-2), var(--midnight) 62%); background-color: var(--midnight); padding: 22px 22px 26px; }")
crep(":root {", ":host {\n  display: block;")
crep("@media (max-width: 980px)", "@container (max-width: 980px)")
crep("@media (max-width: 520px)", "@container (max-width: 520px)")
css += "\n.intro { display: grid; gap: 8px; margin-bottom: 18px; max-width: 46rem; }\n.intro h2 { font: 300 clamp(26px, 4cqi, 38px)/1.1 var(--serif); color: var(--lit); margin: 0; }\n.intro p { font: 300 17px/1.55 var(--serif); color: var(--lit); margin: 0; }\n.intro .sample { font: 400 13px var(--sans); color: var(--dim); }\n"
css = css.replace(".intro p { font: 300 17px/1.55 var(--serif); color: var(--lit); margin: 0; }", ".intro p { font: 300 17px/1.55 var(--serif); color: var(--text); margin: 0; }")

# ---------- HTML ----------
html = s[s.index('<div class="wrap">'): s.rindex('<script>')]
html = re.sub(r'<header class="top">.*?</header>\s*', '', html, flags=re.S)
html = re.sub(r'<section class="hero">.*?</section>\s*', '<div class="intro"><h2>The shape of your agreement.</h2><p>Every spoke is a decision between the agency and the client. The rounder the circle, the closer you are. It does not need to be perfect to move forward, only free of deal-breakers.</p><p class="sample">Sample project: Northwind Outfitters and Studio Halcyon. This preview uses sample data.</p></div>\n', html, flags=re.S)
# The dock, glow and toast are fixed to the screen, so they must sit OUTSIDE the
# container: container-type makes layout containment, which would otherwise pin them to it.
cut = html.index('<div class="dock"')
html = '<div class="root">' + html[:cut].strip() + '</div>\n' + html[cut:].strip()

# ---------- JS ----------
js = s[s.rindex('<script>') + 8: s.rindex('</script>')]
def jrep(old, new):
    global js
    assert old in js, old[:70]
    js = js.replace(old, new, 1)
jrep("(function () {\n  'use strict';\n", "")
js = js.rstrip()
assert js.endswith("})();")
js = js[:-5] + "  return stopAll;\n"
jrep("var $ = function (id) { return document.getElementById(id); };", "var $ = function (id) { return root.getElementById(id); };")
jrep("document.addEventListener('click', function (e) {", "root.addEventListener('click', function (e) {")
assert "document.getElementById" not in js and "document.addEventListener" not in js

header = "// @ts-nocheck\n// Generated by concepts/a-line/port.py from concepts/a-line/a-line.html. Edit the page, then re-run the script.\n// The A-Line alignment circle: the project overview shown after sign-in.\n// It runs inside a shadow root so its styles never touch the rest of the app.\n// It uses sample data until the read endpoint for a real room exists.\n"
ts = header + "export const CSS = " + json.dumps(css) + "\n\nexport const HTML = " + json.dumps(html) + "\n\nexport function mount(root) {\n  'use strict';\n" + js + "}\n"
open('apps/web/src/alignment-circle.ts', 'w').write(ts)
open('/tmp/port/alignment-circle.mjs', 'w').write(ts)
print('written', len(ts))
